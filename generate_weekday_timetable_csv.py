import csv
from datetime import datetime

def timefmt(t):
    if not t or t.strip() in ["～", "", None]:
        return ""
    t = t.strip().replace("：", ":")
    if len(t) == 4: t = "0" + t
    if len(t) == 5: t += ":00"
    return t

