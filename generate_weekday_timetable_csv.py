def write_csv(filename, route, data):
    with open(filename, "w", encoding="utf-8", newline="") as f:
        writer = csv.writer(f)
        writer.writerow(["route","direction","departure_time","arrival_time","is_shuttle","shuttle_start","shuttle_end","valid_from","valid_to","remarks","timetable_type"])
        for dep, arr, arr2, remarks in data:
            # シャトル運行区間はis_shuttle=1, shuttle_start/shuttle_endを設定
            if "シャトル" in remarks:
                writer.writerow([route, 0, timefmt(dep), timefmt(arr), 1, timefmt(dep), timefmt(arr), "", "", remarks, 1])
            else:
                writer.writerow([route, 0, timefmt(dep), timefmt(arr), 0, "", "", "", "", remarks, 1])

